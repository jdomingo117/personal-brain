import {openGoalDetails} from './lib/budgetOverviewUI.mjs'
import { randomUUID } from 'node:crypto'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

/** Invoked only inside the guarded disposable provisioner. All tested writes
 * use authenticated UI/Edge calls; SQL is fixture setup and independent proof. */
export async function budgetTaskPanelChecks({repo,newUser,sql,quote,check,signedPage,snapshotSQL,settled,captureRoot='docs/budget-ui/bui-02/captures'}) {
  const u=await newUser(),everyday=randomUUID()
  const account=sql(`INSERT INTO public.accounts(user_id,tenant_id,name,type,balance,currency) VALUES(${quote(u.id)},${quote(u.tenant)},'Unselected task-panel fixture','Liquid',0,'AUD') RETURNING id;`).split('\n')[0]
  const date=sql("SELECT date_trunc('month',now() AT TIME ZONE 'Australia/Sydney')::date;")
  const previousDate=sql("SELECT (date_trunc('month',now() AT TIME ZONE 'Australia/Sydney')-interval '1 month')::date;")
  const command=input=>{
    const s=snapshotSQL(u)
    return JSON.parse(sql(`SELECT public.budget_command(${quote(u.tenant)},${quote(u.id)},${quote(randomUUID())},${quote(JSON.stringify({expected_source:s.source_revision,expected_method:'budget-foundation-v1',plan_id:s.plan?.id,period_id:s.period?.id,expected_plan:s.plan?.version,...input}))}::jsonb,true);`))
  }
  command({action:'save_draft',expected_draft:'0',payload:{currency:'AUD',timezone:'Australia/Sydney',frequency:'monthly',start_date:previousDate,account_ids:[],destination_account_ids:[],income_cents:400000,opening_drawdown_cents:0,lines:[{id:everyday,kind:'everyday',name:'Everyday',allocation_cents:200000,opening_cents:0}]}})
  command({action:'activate',expected_draft:'1',accept_gap:false})
  command({action:'open_next_period',income_cents:400000,accept_gap:false,lines:[{line_id:everyday,amount_cents:200000}]})
  const page=await signedPage(u,1440,true),origin=new URL(page.url()).origin
  const out=resolve(repo,captureRoot);mkdirSync(out,{recursive:true})
  let task=page.getByRole('dialog'),writes=[]
  page.on('request',req=>{if(req.url().includes('/functions/v1/manage-budget'))writes.push(req.postDataJSON())})
  const open=async()=>{
    await page.getByRole('button',{name:'Save for something',exact:true}).click()
    task=page.getByRole('dialog',{name:'Save for something',exact:true})
    await expect(task).toBeFocused()
  }
  const discard=async()=>{
    await task.getByRole('button',{name:'Close',exact:true}).click()
    await task.getByRole('button',{name:'Leave without saving',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  await settled(page)
  await page.getByRole('button',{name:'Add a bill',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeFocused()
  check('unmigrated bill task retains its existing host',await page.getByRole('dialog').evaluate(el=>el instanceof HTMLDialogElement),false)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'Add a bill',exact:true})).toBeFocused()
  await open()
  check('goal pilot uses one native modal outside the masked screen',await task.evaluate(el=>({native:el instanceof HTMLDialogElement,modal:el.matches(':modal'),parent:el.parentElement.tagName,traps:document.querySelectorAll('dialog:modal,[role="dialog"][aria-modal="true"]').length})),{native:true,modal:true,parent:'BODY',traps:1})
  await page.keyboard.press('Shift+Tab')
  await expect.poll(()=>task.evaluate(el=>el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape');await expect(task).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Save for something',exact:true})).toBeFocused()
  check('pristine Escape closes and restores the opener',true)
  await open()
  await task.getByLabel('Name',{exact:true}).fill('Unsaved flight')
  await page.keyboard.press('Escape')
  await expect(task.getByRole('button',{name:'Stay and keep editing'})).toBeFocused()
  await task.getByRole('button',{name:'Stay and keep editing'}).click()
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Unsaved flight')
  await page.mouse.click(10,100)
  await expect(task.getByRole('button',{name:'Leave without saving'})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Unsaved flight')
  check('dirty Escape and outside click share in-panel preservation without nested dialogs',await page.getByRole('dialog').count(),1)
  await discard()
  check('discard creates no command or financial change',[writes.length,snapshotSQL(u).lines.length],[0,1])

  // Real Router PUSH request, initiated programmatically because native modal
  // correctly makes ordinary pointer/keyboard access to the rail inert.
  await open();await task.getByLabel('Name',{exact:true}).fill('Keep across route request')
  await page.locator('nav button[aria-label="Accounts"]').evaluate(el=>el.click())
  await expect(task.getByRole('button',{name:'Stay and keep editing'})).toBeVisible()
  await expect(page).toHaveURL(`${origin}/budget`)
  await task.getByRole('button',{name:'Stay and keep editing'}).click()
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Keep across route request')
  await discard()
  check('in-app route request waits for the task decision',true)

  // Build Router-owned history, then exercise both POP directions.
  await page.getByRole('navigation').getByRole('button',{name:'Accounts',exact:true}).click()
  await expect(page).toHaveURL(`${origin}/accounts`)
  await page.getByRole('navigation').getByRole('button',{name:'Budget',exact:true}).click()
  await expect(page.getByRole('button',{name:'Save for something',exact:true})).toBeEnabled()
  await open();await task.getByLabel('Name',{exact:true}).fill('Retain on back')
  await page.evaluate(()=>history.back())
  await expect(task.getByRole('button',{name:'Stay and keep editing'})).toBeVisible()
  await expect(page).toHaveURL(`${origin}/budget`)
  await task.getByRole('button',{name:'Stay and keep editing'}).click()
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Retain on back')
  await page.evaluate(()=>history.back())
  await task.getByRole('button',{name:'Leave without saving'}).click()
  await expect(page).toHaveURL(`${origin}/accounts`)
  await page.evaluate(()=>history.back())
  await expect(page).toHaveURL(`${origin}/budget`)
  await expect(page.getByRole('button',{name:'Save for something',exact:true})).toBeEnabled()
  await open();await task.getByLabel('Name',{exact:true}).fill('Retain on forward')
  await page.evaluate(()=>history.forward())
  await expect(task.getByRole('button',{name:'Stay and keep editing'})).toBeVisible()
  await expect(page).toHaveURL(`${origin}/budget`)
  await task.getByRole('button',{name:'Stay and keep editing'}).click()
  await discard()
  check('browser back/forward restore URL and retain inputs until explicit leave',true)

  // Geometry and accessibility proof on the actual production task and dirty step.
  for(const width of [320,390,1440])for(const dark of [false,true]){
    await page.setViewportSize({width,height:1000})
    await page.evaluate(dark=>document.documentElement.classList.toggle('dark',dark),dark)
    await open()
    await task.getByLabel('Name',{exact:true}).fill('A flight to look forward to')
    const state=`${width}-${dark?'dark':'light'}`
    check(`${state} goal panel geometry`,await task.evaluate(el=>({overflow:el.scrollWidth>el.clientWidth+1,width:Math.round(el.getBoundingClientRect().width),bodyScroll:getComputedStyle(el.querySelector('.budget-task-body')).overflowY})),{overflow:false,width:width<700?width:560,bodyScroll:'auto'})
    check(`${state} close control stays on one line`,await task.locator('header > button').evaluate(el=>getComputedStyle(el).whiteSpace),'nowrap')
    const scan=await new AxeBuilder({page}).include('.budget-panel').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()
    check(`${state} goal panel automated accessibility`,scan.violations.map(v=>v.id),[])
    await task.screenshot({path:resolve(out,`${state}-goal.png`)})
    await task.getByRole('button',{name:'Close',exact:true}).click()
    const leaveScan=await new AxeBuilder({page}).include('.budget-panel').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()
    check(`${state} dirty decision automated accessibility`,leaveScan.violations.map(v=>v.id),[])
    await task.screenshot({path:resolve(out,`${state}-leave.png`)})
    await task.getByRole('button',{name:'Leave without saving'}).click()
  }
  await page.setViewportSize({width:1440,height:1050})
  await page.evaluate(()=>document.documentElement.classList.remove('dark'))
  await open()
  await task.getByLabel('Name',{exact:true}).fill('Flight ticket')
  await task.getByLabel('Target cost (AUD)',{exact:true}).fill('900')
  await task.getByLabel('Amount per planned contribution (AUD)',{exact:true}).fill('25')
  await task.getByRole('button',{name:'Review impact'}).click()
  sql(`UPDATE public.accounts SET name='Unselected source-change fixture' WHERE id=${quote(account)};`)
  const refreshed=page.waitForResponse(response=>response.url().includes('/functions/v1/query-budget')&&response.request().postDataJSON()?.action==='workspace')
  await page.locator('button[aria-label="Refresh saved data"]').evaluate(el=>el.click())
  await refreshed
  await expect(task.getByRole('button',{name:'Review impact',exact:true})).toBeVisible()
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Flight ticket')
  await expect(task.getByLabel('Amount per planned contribution (AUD)',{exact:true})).toHaveValue('25')
  check('source refresh retains goal input and invalidates prior acceptance',true)
  await task.getByRole('button',{name:'Review impact'}).click()
  const before=snapshotSQL(u),initialWrites=writes.length
  let release,committedResolve
  const held=new Promise(r=>release=r),committed=new Promise(r=>committedResolve=r)
  await page.route('**/functions/v1/manage-budget',async route=>{
    await route.fetch();committedResolve();await held;await route.abort('failed')
  })
  await task.getByRole('button',{name:'Save savings goal',exact:true}).click()
  await committed
  await expect(task.getByRole('button',{name:'Close',exact:true})).toBeDisabled()
  await page.evaluate(()=>history.forward())
  await expect(page).toHaveURL(`${origin}/budget`)
  check('in-flight save blocks close and browser navigation',true)
  release()
  await expect(task.getByRole('button',{name:'Check saved result',exact:true})).toBeEnabled()
  await page.unroute('**/functions/v1/manage-budget')
  const request=writes.at(-1),saved=snapshotSQL(u),goal=saved.lines.find(l=>l.name==='Flight ticket')
  check('goal pilot preserves save intent',{action:request.action,plan:request.plan_id,period:request.period_id,version:request.expected_plan,source:request.expected_source,amount:request.item.amount_cents,target:request.item.target_cents,opening:request.opening_cents,acceptGap:request.accept_gap},{action:'save_item',plan:before.plan.id,period:before.period.id,version:before.plan.version,source:before.source_revision,amount:2500,target:90000,opening:0,acceptGap:false})
  check('goal pilot preserves complete item configuration',request.item,{type:'goal',name:'Flight ticket',target_cents:90000,estimated:true,due_date:null,cadence:'monthly',anchor:date,amount_cents:2500,state:'saving',recurring_id:null,planning_goal_id:null,featured:false,source_account_id:null,source_merchant_key:null})
  check('unknown result retains original request checkpoint',await page.evaluate(id=>Object.values(sessionStorage).some(value=>{try{return JSON.parse(value).request_id===id}catch{return false}}),request.request_id),true)
  await task.screenshot({path:resolve(out,'1440-light-unknown-save.png')})
  await task.getByRole('button',{name:'Close',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Check saved result',exact:true})).toBeEnabled()
  await page.reload()
  await expect(page.getByRole('button',{name:'Check saved result',exact:true})).toBeEnabled({timeout:30000})
  check('reload retains the same unknown goal request',await page.evaluate(id=>Object.values(sessionStorage).some(value=>{try{return JSON.parse(value).request_id===id}catch{return false}}),request.request_id),true)
  // Pending recovery remains guarded even after the task closes.
  await page.getByRole('navigation').getByRole('button',{name:'Accounts',exact:true}).click()
  await expect(page).toHaveURL(`${origin}/budget`)
  // An explicitly accepted document navigation can leave Budget. It must never
  // trap the owner outside the only route that exposes pending-result recovery.
  const allowUnload=dialog=>dialog.accept()
  page.on('dialog',allowUnload)
  await page.goto(`${origin}/accounts`)
  page.off('dialog',allowUnload)
  await page.getByRole('navigation').getByRole('button',{name:'Budget',exact:true}).click()
  await expect(page.getByRole('button',{name:'Check saved result',exact:true})).toBeEnabled()
  check('cross-document return can always reach Budget recovery',true)
  await page.getByRole('button',{name:'Check saved result',exact:true}).click()
  await expect(page.getByRole('button',{name:'Check saved result',exact:true})).toHaveCount(0)
  check('receipt recovery performs no second save',[writes.length-initialWrites,snapshotSQL(u).plan.version],[1,saved.plan.version])
  check('goal saved exact cents once',goal.allocation_cents,2500)
  await openGoalDetails(page,goal.id)
  await page.locator('article').filter({has:page.getByRole('heading',{name:'Flight ticket',exact:true})}).getByRole('button',{name:'Adjust Flight ticket',exact:true}).click()
  task=page.getByRole('dialog',{name:'Adjust your plan',exact:true})
  await expect(task.getByLabel('Amount per planned contribution (AUD)',{exact:true})).toHaveValue('25.00')
  await task.getByLabel('Amount per planned contribution (AUD)',{exact:true}).fill('30')
  await task.getByRole('button',{name:'Review impact'}).click()
  const editWrites=writes.length
  await page.route('**/functions/v1/manage-budget',async route=>{await route.fetch();await route.abort('failed')})
  await task.getByRole('button',{name:'Save savings goal',exact:true}).click()
  await expect(task.getByRole('button',{name:'Check saved result',exact:true})).toBeEnabled()
  await page.unroute('**/functions/v1/manage-budget')
  await task.getByRole('button',{name:'Check saved result',exact:true}).click()
  await expect(task).toHaveCount(0)
  check('existing goal edit recovers inside the panel and closes without a duplicate write',[writes.length-editWrites,snapshotSQL(u).lines.find(l=>l.id===goal.id).allocation_cents],[1,3000])
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Undo last budget change',exact:true}).click()
  await openGoalDetails(page,goal.id)
  await expect(page.locator('article').filter({has:page.getByRole('heading',{name:'Flight ticket',exact:true})})).toContainText('$25.00')
  check('guarded Undo restores prior goal amount without changing everyday allocation',[snapshotSQL(u).lines.find(l=>l.id===goal.id).allocation_cents,snapshotSQL(u).lines.find(l=>l.id===everyday).allocation_cents],[2500,200000])
  await page.getByRole('button',{name:'Refresh saved data',exact:true}).click()
  await expect(page.getByRole('button',{name:'Previous saved budget',exact:true})).toBeEnabled()
  await open();await task.getByLabel('Name',{exact:true}).fill('Retain on period change')
  await page.locator('button[aria-label="Previous saved budget"]').evaluate(el=>el.click())
  await expect(task.getByRole('button',{name:'Stay and keep editing'})).toBeVisible()
  await expect(page).toHaveURL(`${origin}/budget`)
  await task.getByRole('button',{name:'Stay and keep editing'}).click()
  await expect(task.getByLabel('Name',{exact:true})).toHaveValue('Retain on period change')
  await page.locator('button[aria-label="Previous saved budget"]').evaluate(el=>el.click())
  await task.getByRole('button',{name:'Leave without saving'}).click()
  await expect(page).toHaveURL(/budgetPeriod=/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  check('saved-period selection shares the dirty exit policy and preserves indexed URL history',typeof await page.evaluate(()=>history.state.idx),'number')
  await page.close()
}
