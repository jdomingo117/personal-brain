test('desktop, tablet and phone support both themes without content or task overflow', async ({ page }) => {
  for (const dark of [false, true]) {
    if (dark) await page.getByRole('button', { name: 'Use dark appearance' }).click()
    for (const width of [1440, 1024, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      const overflow = await page.evaluate(() => [...document.querySelectorAll<HTMLElement>('.bc-stage, .bc-scroll, .bc-page, .bc-category, .bc-goal-card')].filter(el => el.getBoundingClientRect().width > 0).filter(el => el.scrollWidth > el.clientWidth + 1).map(el => el.className))
      expect(overflow, `${width}px ${dark ? 'dark' : 'light'}`).toEqual([])
      await page.getByRole('button', { name: 'Save for something', exact: true }).click()
      const dialog = page.getByRole('dialog')
      expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
      await page.keyboard.press('Escape')
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Phone preview', exact: true }).click()
  await page.getByRole('button', { name: 'Save for something', exact: true }).click()
  expect(await page.getByRole('dialog').evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(430)
  await page.keyboard.press('Escape')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Try setup' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
})

